import importlib.resources
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import kotlin_tzif as kt  # noqa: E402


def tzif(key):
    return importlib.resources.files("tzdata.zoneinfo").joinpath(*key.split("/")).read_bytes()


def kotlin_array(data, name):
    # Generated Kotlin writes bytes as ints; some may be signed. Mix both to test the decode.
    nums = [(b - 256 if (b > 127 and i % 2) else b) for i, b in enumerate(data)]
    return f"/* x */\ninternal val {name} get() = byteArrayOf(\n  " + ", ".join(map(str, nums)) + "\n)\n"


def make_src(tmp, zones, footer_hack=None):
    d = tmp / "commonMain"
    d.mkdir()
    lines = ["/* AUTOGENERATED FROM ZONE INFO DATABASE v.2026f */", "", "internal fun zoneDataByName(name: String): ByteArray = when(name) {"]
    for i, z in enumerate(zones):
        data = tzif(z)
        if footer_hack and z in footer_hack:
            data = data.rstrip(b"\n").rsplit(b"\n", 1)[0] + b"\n" + footer_hack[z] + b"\n"
        lines.append(f'    "{z}" -> tzData{i}')
        (d / f"tzData{i}.kt").write_text(kotlin_array(data, f"tzData{i}"))
    lines.append("}")
    (d / "tzData.kt").write_text("\n".join(lines))
    return tmp


def test_reads_offsets_and_version(tmp_path, capsys):
    root = make_src(tmp_path, ["America/Havana", "America/Edmonton"])
    assert kt.main([str(root), "America/Havana", "America/Edmonton", "Nope/Zone", "--at", "2026-01-15T12:00Z"]) == 0
    out = capsys.readouterr().out
    assert "database: 2026f" in out
    assert "America/Havana\t-5" in out
    assert "America/Edmonton\t-7" in out
    assert "Nope/Zone\tnot in data" in out


def test_unparseable_footer_reported_not_crash(tmp_path, capsys):
    root = make_src(tmp_path, ["Africa/Casablanca"], {"Africa/Casablanca": b"%z-1"})
    assert kt.main([str(root), "Africa/Casablanca", "--at", "2040-01-15T12:00Z"]) == 0
    out = capsys.readouterr().out
    assert "unreadable" in out and "%z-1" in out
