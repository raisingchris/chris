#!/usr/bin/env python3
"""Rules that live in comments: what have a repo's maintainers SAID about AI?

agent_rules.py reads files. Twice (black, poetry) the real rule was in a
maintainer's comment on an issue or PR. This finds those comments.

    python3 maintainer_ai_comments.py owner/repo [--since 2025-01-01] [--items 20]

It searches the repo's issues and PRs for AI words, reads each hit's comments
(and its body), and prints only text written by MEMBER / OWNER / COLLABORATOR
that itself mentions AI. Read-only; uses `gh api`.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import urllib.parse

AI_RE = re.compile(
    r"\b(AI|LLMs?|ChatGPT|Copilot|Claude|GPT-?\d?|Cursor|agentic|AI[- ]generated|"
    r"generated by AI|language model|vibe[- ]coded?)\b"
)
STAFF = {"MEMBER", "OWNER", "COLLABORATOR"}
QUERY_TERMS = '"AI-generated" OR "LLM" OR "ChatGPT" OR "Copilot" OR "AI generated"'


def gh(path: str):
    out = subprocess.run(["gh", "api", path], capture_output=True, text=True)
    if out.returncode != 0:
        return None
    return json.loads(out.stdout)


def mentions_ai(text: str | None) -> bool:
    return bool(text) and bool(AI_RE.search(text))


def staff_ai_texts(item: dict, comments: list[dict]) -> list[dict]:
    """Pick the item body and comments that are by staff AND mention AI."""
    found = []
    entries = [dict(item, html_url=item.get("html_url"))] + comments
    for c in entries:
        if c.get("author_association") in STAFF and mentions_ai(c.get("body")):
            found.append({
                "who": (c.get("user") or {}).get("login"),
                "assoc": c.get("author_association"),
                "date": (c.get("created_at") or "")[:10],
                "url": c.get("html_url"),
                "text": c.get("body") or "",
            })
    return found


def snippet(text: str, width: int = 240) -> str:
    m = AI_RE.search(text)
    start = max(0, (m.start() if m else 0) - width // 2)
    return " ".join(text[start:start + width].split())


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("repo")
    ap.add_argument("--since", default="2025-01-01")
    ap.add_argument("--items", type=int, default=20)
    a = ap.parse_args(argv)
    q = f"repo:{a.repo} ({QUERY_TERMS}) updated:>={a.since}"
    res = gh("search/issues?per_page=%d&sort=updated&q=%s" % (a.items, urllib.parse.quote(q)))
    if res is None:
        print(f"{a.repo}: search failed", file=sys.stderr)
        return 2
    total = res.get("total_count", 0)
    hits = []
    for it in res.get("items", []):
        comments = gh(f"repos/{a.repo}/issues/{it['number']}/comments?per_page=100") or []
        hits += staff_ai_texts(it, comments)
    print(f"{a.repo}: {total} items match, read {len(res.get('items', []))}, staff AI texts {len(hits)}")
    for h in hits:
        print(f"  {h['date']} {h['who']} ({h['assoc']}) {h['url']}\n    {snippet(h['text'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
